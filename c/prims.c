/* prims.c -- the table of primitive functions. */
#include "lisp.h"

PrimFn primtab[NPRIM];
int pmin[NPRIM], pmax[NPRIM];

Ref callprim(int id, Ref *av, long n)
{
    return primtab[id](av, n);
}

void registerprim(const char *name, int id, int mn, int mx)
{
    Ref s = intern(name), c = newcell(T_PRIM);
    csid[c] = (unsigned char)id;
    XS(c) = xstrdup(name);
    ccdr[s] = c;
    pmin[id] = mn;
    pmax[id] = mx;
}

